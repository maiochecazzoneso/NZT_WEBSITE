_SQL_WORDS = r"(SELECT|INSERT|UPDATE|DELETE|WHERE|FROM|CREATE|DROP|ALTER|TRUNCATE|GRANT)\b"
_FORBIDDEN = [
    re.compile(r"""\bf["'][^"'\n]*""" + _SQL_WORDS, re.IGNORECASE),  # f-string SQL
    re.compile(r"""["'][^"'\n]*""" + _SQL_WORDS + r"""[^"'\n]*["']\s*%\s*[(\w]""", re.I),
    re.compile(r"""["'][^"'\n]*""" + _SQL_WORDS + r"""[^"'\n]*["']\s*\.format\(""", re.I),
    re.compile(r"""["'][^"'\n]*""" + _SQL_WORDS + r"""[^"'\n]*["']\s*\+""", re.I),
    re.compile(r"""text\(\s*f["']"""),
    re.compile(r"exec_driver_sql\("),
]


def test_no_string_built_sql():
    offenders: list[str] = []
    for path in SCANNED:
        for lineno, line in enumerate(path.read_text().splitlines(), 1):
            if line.lstrip().startswith("#"):
                continue
            for pattern in _FORBIDDEN:
                if pattern.search(line):
                    offenders.append(f"{path.relative_to(ROOT)}:{lineno}: {line.strip()}")
    assert offenders == []


def test_raw_text_sql_is_constant():
    # Only these constant raw statements exist; everything else is SQLAlchemy Core/ORM.
    found = []
    for path in SCANNED:
        found += re.findall(r"text\((['\"].*?['\"])\)", path.read_text())
    assert sorted(set(found)) == sorted(
        {
            '"SELECT 1"',
            '"uuid_generate_v4()"',
            '"true"',
            '"false"',
            '"lower(email)"',
            '"created_at DESC"',
            """'CREATE EXTENSION IF NOT EXISTS "uuid-ossp"'""",
            """'DROP EXTENSION IF EXISTS "uuid-ossp"'""",
        }
    )
