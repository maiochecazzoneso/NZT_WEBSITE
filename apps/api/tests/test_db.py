async def test_schema_matches_spec(migrator_conn: asyncpg.Connection):
    cols = await migrator_conn.fetch(
        "SELECT table_name, column_name, is_nullable, data_type FROM information_schema.columns "
        "WHERE table_schema = 'public' AND table_name <> 'alembic_version'"
    )
    by = {(r["table_name"], r["column_name"]): r for r in cols}
    assert by[("download_logs", "user_id")]["is_nullable"] == "YES"  # D-A3
    assert by[("download_logs", "ip_address")]["data_type"] == "inet"
    assert by[("users", "password_hash")]["is_nullable"] == "YES"
    assert by[("refresh_tokens", "token_hash")]["data_type"] == "character varying"
    indexes = {
        r["indexname"]: r["indexdef"]
        for r in await migrator_conn.fetch(
            "SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'public'"
        )
    }
    assert "lower((email)::text)" in indexes["idx_users_email_lower"]
    assert "UNIQUE" in indexes["idx_users_email_lower"]
    assert "created_at DESC" in indexes["idx_download_audit"]
    for name in (
        "idx_identities_user_id",
        "idx_families_user",
        "idx_refresh_token_lookup",
        "idx_entitlements_lookup",
    ):
        assert name in indexes
    fk = await migrator_conn.fetchval(
        "SELECT confdeltype::text FROM pg_constraint WHERE conrelid = 'download_logs'::regclass "
        "AND contype = 'f'"
    )
    assert fk == "n"  # ON DELETE SET NULL


async def test_case_insensitive_unique_email(migrator_conn: asyncpg.Connection):
    await migrator_conn.execute("INSERT INTO users (email) VALUES ('A@x.com')")
    with pytest.raises(asyncpg.UniqueViolationError):
        await migrator_conn.execute("INSERT INTO users (email) VALUES ('a@X.com')")


async def test_app_role_cannot_ddl():
    conn = await asyncpg.connect(APP_DSN)
    try:
        role = await conn.fetchrow(
            "SELECT rolsuper, rolcreatedb, rolcreaterole FROM pg_roles WHERE rolname = current_user"
        )
        assert tuple(role) == (False, False, False)
        for stmt in (
            "CREATE TABLE evil (id int)",
            "DROP TABLE users",
            "ALTER TABLE users ADD COLUMN evil int",
            "TRUNCATE users",
            "CREATE INDEX evil_idx ON users (email)",
            "CREATE SCHEMA evil",
            "CREATE TEMP TABLE evil_tmp (id int)",
            "CREATE FUNCTION public.evil() RETURNS int LANGUAGE sql AS 'SELECT 1'",
        ):
            with pytest.raises(asyncpg.InsufficientPrivilegeError):
                await conn.execute(stmt)
        # DML is allowed.
        await conn.execute("INSERT INTO users (email) VALUES ($1)", "dml@x.com")
        assert await conn.fetchval("SELECT count(*) FROM users") == 1
        await conn.execute("UPDATE users SET is_verified = TRUE")
        await conn.execute("DELETE FROM users")
    finally:
        await conn.close()


