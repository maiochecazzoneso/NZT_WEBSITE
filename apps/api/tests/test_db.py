ROOT = Path(__file__).resolve().parents[1]
SCANNED = [*sorted((ROOT / "src").rglob("*.py")), *sorted((ROOT / "alembic").rglob("*.py"))]


def test_migrations_downgrade_base_and_upgrade_head():
    cfg = alembic_config()
    command.downgrade(cfg, "base")
    command.upgrade(cfg, "head")
    buf = io.StringIO()
    cfg.stdout = buf
    command.current(cfg)
    assert "0002 (head)" in buf.getvalue()


